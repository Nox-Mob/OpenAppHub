#!/usr/bin/env node
// The suite-wide open-source license list (SHARED-SPEC §10.3): every library used across the
// OpenAppHub suite, by name and license, for the About page in the hub and every app.
//
//   node scripts/collect-licenses.mjs ../opencharterapp ../openboardapp ../openledgerapp ../openapphub-docs
//
// Run from the hub's root, with each repository checked out and its packages installed. It reads
// the hub's npm packages and each listed repository's (shared/licenses/generate.mjs). Rust packages
// (OpenLedgerApp's desktop edition) aren't part of the web suite: the desktop build shows them
// itself (shared/licenses/cargo.mjs). It writes:
// - shared/licenses/suite.json: name and license only (the About page), synced to every app;
// - public/third-party-licenses.txt: every license text, served at /third-party-licenses.txt.
// Run it before syncing shared/ to the apps whenever an app's packages change.
import { existsSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { collectNpm, noticesText } from "../shared/licenses/generate.mjs";

const repos = process.argv.slice(2).map((r) => resolve(r));
if (!repos.length) {
  console.error(
    "Usage: node scripts/collect-licenses.mjs ../opencharterapp ../openboardapp ../openledgerapp ../openapphub-docs",
  );
  process.exit(1);
}

const all = [];
for (const root of [process.cwd(), ...repos]) {
  if (!existsSync(join(root, "node_modules"))) {
    console.error(`${root}: install its packages first (npm ci or bun install).`);
    process.exit(1);
  }
  all.push(...collectNpm(root).packages);
}

// One row per name and license (versions left out); license texts kept once each.
const byKey = new Map();
for (const p of all) {
  const license = p.license === "UNKNOWN" ? "Not stated" : p.license;
  const key = `${p.name}\u0000${license}`;
  const entry = byKey.get(key) ?? { name: p.name, license, texts: new Set() };
  if (p.text) entry.texts.add(p.text);
  byKey.set(key, entry);
}
const entries = [...byKey.values()].sort(
  (a, b) => a.name.localeCompare(b.name) || a.license.localeCompare(b.license),
);

writeFileSync(
  "shared/licenses/suite.json",
  JSON.stringify(
    {
      note: "Generated by scripts/collect-licenses.mjs. Don't edit by hand.",
      libraries: entries.map(({ name, license }) => ({ name, license })),
    },
    null,
    2,
  ) + "\n",
);
writeFileSync(
  "public/third-party-licenses.txt",
  noticesText(
    "Open-source software in the OpenAppHub suite",
    entries.map((e) => ({ name: e.name, license: e.license, text: [...e.texts].join("\n\n") })),
  ),
);
console.log(
  `Wrote ${entries.length} libraries to shared/licenses/suite.json and public/third-party-licenses.txt.`,
);
